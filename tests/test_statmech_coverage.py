class TestPow10:

    def test_matches_plain_exponentiation_in_range(self):
        for x in (-10.0, 0.0, 3.5, 250.0):
            assert float(S._pow10(x)) == pytest.approx(10.0 ** x, rel=1e-14)

    def test_clamps_instead_of_overflowing(self):
        """Julia lets these overflow to Inf and treats that as a failed Newton
        step; clamping keeps the residual finite but still enormous.

        Compared with a tolerance, not exactly: XLA's ``pow`` and CPython's
        ``**`` disagree by one ulp on the GPU backend (9.999999999999999e+299 vs
        1e+300) while agreeing exactly on CPU.  What matters here is that the
        clamp fires at the documented exponent, not that two different
        libraries' pow implementations round identically.
        """
        assert float(S._pow10(1e6)) == pytest.approx(10.0 ** 300, rel=1e-15)
        assert float(S._pow10(-1e6)) == pytest.approx(10.0 ** -300, rel=1e-15)
        assert np.isfinite(float(S._pow10(1e6)))

    def test_is_jittable_and_differentiable(self):
        assert float(jax.jit(S._pow10)(2.0)) == pytest.approx(100.0)
        g = float(jax.grad(S._pow10)(2.0))
        assert g == pytest.approx(100.0 * np.log(10.0), rel=1e-12)


class TestHummerMihalasW:
    """The occupation-probability correction used by ``continuum.H_I_bf``.

    Note there is a *second* implementation in
    ``korg.hydrogen_line_absorption``; see TestDuplicateImplementations.
    """

    LIVE = dict(T=5778.0, nH=1.8e17, nHe=1.6e16, ne=1e14)

    def test_matches_julia_standard(self, chem_ref):
        worst = 0.0
        for key, ref in chem_ref["statmech"]["hummer_mihalas_w"]["standard"].items():
            T, n_eff, nH, nHe, ne = (float(x) for x in key.split("_"))
            got = float(S.hummer_mihalas_w(T, n_eff, nH, nHe, ne))
            assert got == pytest.approx(float(ref), rel=1e-12), key
            if ref:
                worst = max(worst, abs(got / float(ref) - 1.0))
        assert worst < 1e-12

    def test_matches_julia_hubeny(self, chem_ref):
        for key, ref in chem_ref["statmech"]["hummer_mihalas_w"]["hubeny"].items():
            T, n_eff, nH, nHe, ne = (float(x) for x in key.split("_"))
            got = float(S.hummer_mihalas_w(T, n_eff, nH, nHe, ne,
                                           use_hubeny_generalization=True))
            assert got == pytest.approx(float(ref), rel=1e-12), key

    def test_w_is_a_probability(self):
        for n_eff in (1.0, 3.0, 3.5, 10.0, 40.0):
            w = float(S.hummer_mihalas_w(n_eff=n_eff, **self.LIVE))
            assert 0.0 <= w <= 1.0

    def test_high_levels_are_dissolved(self):
        """w → 0 as n_eff grows: the level merges into the continuum."""
        ws = [float(S.hummer_mihalas_w(n_eff=n, **self.LIVE))
              for n in (1.0, 10.0, 40.0, 100.0)]
        assert ws == sorted(ws, reverse=True)
        assert ws[-1] < 1e-6

    def test_denser_plasma_dissolves_more(self):
        sparse = float(S.hummer_mihalas_w(5778.0, 20.0, 1e12, 1e11, 1e9))
        dense = float(S.hummer_mihalas_w(5778.0, 20.0, 1e18, 1e17, 1e15))
        assert dense < sparse

    def test_K_switches_at_n_eff_equals_three(self):
        """K is 1 for n_eff <= 3 and the H&M 4.24 expression above it; the switch
        is continuous enough that w stays monotone across it."""
        below = float(S.hummer_mihalas_w(n_eff=2.9, **self.LIVE))
        at = float(S.hummer_mihalas_w(n_eff=3.0, **self.LIVE))
        above = float(S.hummer_mihalas_w(n_eff=3.1, **self.LIVE))
        assert below >= at >= above

    def test_hubeny_branch_gives_a_different_answer(self):
        """Both branches must actually be reachable and distinguishable."""
        std = float(S.hummer_mihalas_w(n_eff=5.0, **self.LIVE))
        hub = float(S.hummer_mihalas_w(n_eff=5.0, use_hubeny_generalization=True,
                                       **self.LIVE))
        assert std != hub
        assert 0.0 < hub <= 1.0

    @pytest.mark.parametrize("ne,T", [(0.0, 5778.0), (5.0, 5778.0), (1e14, 5.0)])
    def test_hubeny_guard_falls_back_to_zero_charged_term(self, ne, T):
        """Below (ne > 10) & (T > 10) the Hubeny charged term is dropped."""
        w = float(S.hummer_mihalas_w(T, 5.0, 1.8e17, 1.6e16, ne,
                                     use_hubeny_generalization=True))
        assert np.isfinite(w) and 0.0 < w <= 1.0


