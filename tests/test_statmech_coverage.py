class TestPrecompute:

    def test_shapes_and_dtypes(self, eq_data):
        assert eq_data.ionization_energies.shape == (S.MAX_ATOMIC_NUMBER, 3)
        assert eq_data.partition_func_values.shape[:2] == (S.MAX_ATOMIC_NUMBER, 3)
        assert eq_data.mol_atom_consume.shape == (eq_data.n_molecules,
                                                  S.MAX_ATOMIC_NUMBER)
        assert eq_data.mol_atoms_array.shape == (eq_data.n_molecules, 6)
        assert eq_data.n_molecules > 0

    def test_zero_molecule_data_is_supported(self, eq_data_no_molecules):
        """The ``n_molecules == 0`` branch — an atoms-only equilibrium."""
        data = eq_data_no_molecules
        assert data.n_molecules == 0
        assert data.mol_charges.shape == (0,)
        assert data.mol_atom_consume.shape == (0, S.MAX_ATOMIC_NUMBER)

    def test_zero_molecule_density_helper_returns_empty(self, eq_data_no_molecules,
                                                        abundances):
        data = eq_data_no_molecules
        nf = jnp.ones(S.MAX_ATOMIC_NUMBER)
        out = S._compute_mol_densities_jit(5000.0, 1e16, 1e13, abundances, nf, data)
        assert out.shape == (0,)

    def test_hydrogen_third_partition_function_is_a_placeholder(self, eq_data):
        """H III does not exist, but a NaN there would poison the wIII cotangent,
        so precompute installs a synthetic 2-knot spline."""
        assert int(eq_data.pf_orig_n[0, 2]) >= 2
        assert np.all(np.isfinite(np.asarray(eq_data.pf_orig_u[0, 2, :2])))

    def test_atomic_partition_spline_matches_the_original(self, eq_data,
                                                          partition_funcs):
        from korg.species import Species, Formula
        for Z, charge in [(1, 0), (2, 0), (26, 0), (26, 1), (20, 1)]:
            sp = Species(Formula(Z), charge)
            if sp not in partition_funcs:
                continue
            for T in (3000.0, 5778.0, 12000.0):
                log_T = np.log(T)
                got = float(S._eval_atomic_pf_jit(
                    log_T,
                    eq_data.pf_orig_t[Z - 1, charge],
                    eq_data.pf_orig_u[Z - 1, charge],
                    eq_data.pf_orig_h[Z - 1, charge],
                    eq_data.pf_orig_z[Z - 1, charge],
                    eq_data.pf_orig_n[Z - 1, charge]))
                expected = float(partition_funcs[sp](log_T))
                assert got == pytest.approx(expected, rel=1e-9), f"Z={Z} q={charge} T={T}"

    @pytest.mark.parametrize("Z", [12, 20, 26])
    def test_interp_partition_func_uses_one_based_atomic_number(self, eq_data,
                                                                partition_funcs, Z):
        """Regression: it indexed ``partition_func_values[Z]`` instead of
        ``[Z - 1]``, so it returned U of element Z+1 (U(Co I) for Fe I).

        It has no callers in the package, which is why nothing caught it.
        """
        from korg.species import Species, Formula
        sp = Species(Formula(Z), 0)
        wrong = Species(Formula(Z + 1), 0)
        for T in (3000.0, 5778.0, 12000.0):
            got = float(S._interp_partition_func(np.log(T), Z, 0, eq_data))
            expected = float(partition_funcs[sp](np.log(T)))
            wrong_val = float(partition_funcs[wrong](np.log(T)))
            # linear interpolation on the tabulated grid, so allow a little slack
            assert got == pytest.approx(expected, rel=2e-3), f"Z={Z} T={T}"
            assert abs(got - expected) < abs(got - wrong_val), \
                f"Z={Z} T={T}: still returning element Z+1"

    def test_scalar_and_vectorised_log_nK_agree(self, eq_data, log_K):
        """``_get_log_nK_jit`` (one molecule) vs ``_mol_log_nK_all_jit`` (all)."""
        T = 5000.0
        all_vals = np.asarray(S._mol_log_nK_all_jit(T, eq_data))
        for idx in (0, 1, 5, eq_data.n_molecules - 1):
            one = float(S._get_log_nK_jit(idx, np.log(T), eq_data))
            if np.isfinite(all_vals[idx]):
                assert one == pytest.approx(all_vals[idx], rel=1e-12), f"mol {idx}"

    def test_cubic_spline_eval_logK_is_finite_on_the_grid(self, eq_data):
        for T in (2500.0, 5000.0, 15000.0):
            v = float(S._cubic_spline_eval_logK(np.log(T), eq_data, 0))
            assert np.isfinite(v)


