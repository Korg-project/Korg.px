    def test_forward_and_reverse_mode_through_the_solver_agree(self, eq_data,
                                                               abundances,
                                                               layer_kernels):
        """Both modes work and give the same answer.

        ``_chem_eq_solve_log`` carries a ``custom_jvp`` whose rule is
        ``dy = -J⁻¹ ∂F/∂θ`` for θ = (T, n_total, abundances).  Reverse mode has
        always been correct; forward mode used to return NaN in all 93
        components, and this test previously pinned that.  The cause was not the
        rule but a guard inside ``_chem_eq_log_terms``:
        ``log10(maximum(wIII, 1e-320))``.  1e-320 is subnormal, XLA flushes
        subnormals to zero, so the floor never applied, and hydrogen --- which
        has no doubly ionized state, so wIII[0] is exactly 0 --- produced
        log10(0) = -Inf with a 1/0 derivative meeting a zero tangent.  It showed
        up in exactly the two residual components n_III[0] enters: index 0
        (hydrogen's nucleus balance) and index 92 (charge balance).
        """
        T, nt = 5778.0, 1e17
        ne_g, nf_g = S.picard_chemical_equilibrium_guess(T, nt, 1e14, abundances,
                                                        eq_data)
        args = (jnp.float64(nt), ne_g, nf_g, abundances)

        rev = float(layer_kernels.d_ne_dT(jnp.float64(T), *args))
        fwd = float(layer_kernels.jacfwd_T(jnp.float64(T), *args))
        assert np.isfinite(rev) and np.isfinite(fwd)
        assert fwd == pytest.approx(rev, rel=1e-12)
        assert fwd == pytest.approx(
            _central_difference(lambda t: layer_kernels.at(t, nt, ne_g, nf_g,
                                                           abundances), T),
            rel=1e-5)

    def test_custom_jvp_rule_is_the_implicit_function_theorem(self, eq_data,
                                                              abundances):
        """The registered tangent is exactly −J⁻¹ ∂F/∂T.

        Written to compare the *finite* structure rather than using
        ``assert_allclose``'s default ``equal_nan=True``: when both sides were
        NaN (see the test above, before the subnormal-floor fix) an allclose
        comparison passed vacuously.  Keeping the mask comparison means it stays
        honest if a NaN ever comes back.
        """
        T, nt = 5778.0, 1e17
        ne_g, nf_g = S.picard_chemical_equilibrium_guess(T, nt, 1e14, abundances,
                                                        eq_data)
        y0 = jnp.concatenate([
            jnp.log10(jnp.clip(nf_g * abundances * (nt - ne_g), 1e-99, jnp.inf)),
            jnp.array([jnp.log10(ne_g)])])

        y, dy = jax.jvp(lambda t: S._chem_eq_solve_log(t, nt, abundances, eq_data, y0),
                        (T,), (1.0,))
        assert np.all(np.isfinite(np.asarray(y))), "the primal solution is healthy"

        J = S._chem_eq_log_jacobian(y, T, nt, abundances, eq_data, 0.0)
        dF = jax.jvp(lambda t: S._chem_eq_log_residuals(y, t, nt, abundances, eq_data),
                     (T,), (1.0,))[1]
        expected = np.asarray(-jnp.linalg.solve(J, dF))
        dy = np.asarray(dy)
        np.testing.assert_array_equal(np.isnan(dy), np.isnan(expected))
        finite = ~np.isnan(dy)
        if finite.any():
            np.testing.assert_allclose(dy[finite], expected[finite], rtol=1e-8)

