class TestJit:

    def test_geometry_from_a_traced_radius_jits(self):
        layers = _shell_layers(4)
        f = jax.jit(lambda R: ShellAtmosphere(layers, R).photosphere_correction)
        R0 = 3.0e10
        assert float(f(R0)) == pytest.approx(
            ShellAtmosphere(layers, R0).photosphere_correction, rel=1e-14)

    def test_radii_from_a_traced_radius_jit(self):
        layers = _shell_layers(4)
        out = jax.jit(lambda R: ShellAtmosphere(layers, R).r)(3.0e10)
        np.testing.assert_allclose(np.asarray(out),
                                   ShellAtmosphere(layers, 3.0e10).r, rtol=1e-14)

    def test_read_model_atmosphere_cannot_be_jitted(self):
        """The reader does Python file I/O and ``float()`` on parsed text.

        There is no traced value to thread through it, so this is pinned as a
        permanent limitation rather than a coverage gap.
        """
        @jax.jit
        def f(x):
            atm = read_model_atmosphere(str(SUN_MOD))
            return x * atm.T[0]

        # the reader itself traces fine (it ignores x); what cannot work is
        # making the *file contents* depend on a traced value:
        @jax.jit
        def g(i):
            return read_model_atmosphere(str(SUN_MOD)).T[int(i)]

        assert np.isfinite(float(f(2.0)))
        with pytest.raises(jax.errors.ConcretizationTypeError):
            g(0)
