# 2. High-precision agreement with Korg.jl
# ===========================================================================

class TestAgreementWithKorgJl:
    """These are exact quantities: file parsing plus one multiply/add.

    Nothing here goes through the opacity stack, so machine-precision
    tolerances are appropriate and are used.
    """

    def test_marcs_parse_matches_julia_exactly(self, julia_ref, sun_atm):
        ref = julia_ref["marcs_sun"]
        assert type(sun_atm).__name__ == ref["type"]
        assert sun_atm.n_layers == ref["n_layers"]
        assert sun_atm.reference_wavelength == ref["reference_wavelength"]
        np.testing.assert_allclose(sun_atm.tau_ref, ref["tau_ref"], rtol=1e-15)
        np.testing.assert_allclose(sun_atm.z, ref["z"], rtol=0, atol=0)
        np.testing.assert_allclose(sun_atm.T, ref["temp"], rtol=0, atol=0)
        np.testing.assert_allclose(sun_atm.ne, ref["electron_number_density"],
                                   rtol=1e-15)
        np.testing.assert_allclose(sun_atm.n_total, ref["number_density"],
                                   rtol=1e-15)

    def test_shell_radii_match_julia_exactly(self, julia_ref, sun_atm):
        for case in julia_ref["shell_geometry"]:
            shell = ShellAtmosphere.from_planar(sun_atm, case["R"])
            np.testing.assert_allclose(shell.r, case["radii"], rtol=1e-15,
                                       err_msg=f"radii for R={case['R']}")

    def test_photosphere_correction_matches_julia_exactly(self, julia_ref, sun_atm):
        """Korg.jl's ``radii[1]^2 / atm.R^2``, to 1e-15."""
        for case in julia_ref["shell_geometry"]:
            shell = ShellAtmosphere.from_planar(sun_atm, case["R"])
            assert shell.photosphere_correction == pytest.approx(
                case["photosphere_correction"], rel=1e-15), \
                f"photosphere_correction for R={case['R']}"

    def test_the_extended_case_is_a_large_correction(self, julia_ref, sun_atm):
        """Guard the discriminating power of the end-to-end spherical test.

        The smallest reference radius is chosen so that dropping the
        correction is a ~69% flux error, not a rounding difference.
        """
        smallest = min(julia_ref["shell_geometry"], key=lambda c: c["R"])
        assert smallest["photosphere_correction"] > 1.5


