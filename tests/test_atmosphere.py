def _write_mod(tmp_path, lines, name="model.mod"):
    p = tmp_path / name
    p.write_text("".join(lines))
    return str(p)


class TestMarcsReader:

    def test_solar_model_parses_all_declared_layers(self, sun_atm):
        assert sun_atm.n_layers == 56
        assert sun_atm.reference_wavelength == 5e-5

    def test_number_densities_follow_the_ideal_gas_law(self, sun_atm, sun_mod_lines):
        """n = Pg/(kT), ne = Pe/(kT), read from the fixed-width columns."""
        header = next(i for i, l in enumerate(sun_mod_lines) if "lgTauR" in l)
        row = sun_mod_lines[header + 1]
        T = float(row[29:36])
        Pe = float(row[38:48])
        Pg = float(row[48:60])
        assert sun_atm.T[0] == pytest.approx(T, rel=0, abs=0)
        assert sun_atm.ne[0] == pytest.approx(Pe / (T * kboltz_cgs), rel=1e-15)
        assert sun_atm.n_total[0] == pytest.approx(Pg / (T * kboltz_cgs), rel=1e-15)

    def test_z_is_minus_depth(self, sun_atm, sun_mod_lines):
        header = next(i for i, l in enumerate(sun_mod_lines) if "lgTauR" in l)
        depth = float(sun_mod_lines[header + 1][18:28])
        assert sun_atm.z[0] == -depth

    def test_a_radius_other_than_one_gives_a_shell_atmosphere(self, tmp_path,
                                                              sun_mod_lines):
        """MARCS marks spherical models by a radius line that is not 1.0 cm."""
        lines = list(sun_mod_lines)
        i = next(j for j, l in enumerate(lines) if "adius" in l)
        lines[i] = "  7.0000E+10 Radius [cm] at Tau(Rosseland)=1.0\n"
        atm = read_model_atmosphere(_write_mod(tmp_path, lines))
        assert isinstance(atm, ShellAtmosphere)
        assert atm.R_photosphere == 7.0e10
        assert atm.n_layers == 56
        np.testing.assert_allclose(atm.r, 7.0e10 + atm.z, rtol=0)

    def test_spherical_branch_builds_real_layers(self, tmp_path, sun_mod_lines,
                                                 sun_atm):
        """Regression: the shell branch used to raise ``TypeError``.

        ``ShellAtmosphereLayer`` was constructed with ``temp=`` but its field
        is called ``temperature``, so *every* spherical MARCS model failed to
        load.  The layer data must otherwise be identical to the planar parse.
        """
        lines = list(sun_mod_lines)
        i = next(j for j, l in enumerate(lines) if "adius" in l)
        lines[i] = "  7.0000E+10 Radius\n"
        atm = read_model_atmosphere(_write_mod(tmp_path, lines))
        np.testing.assert_array_equal(atm.T, sun_atm.T)
        np.testing.assert_array_equal(atm.ne, sun_atm.ne)
        np.testing.assert_array_equal(atm.n_total, sun_atm.n_total)
        np.testing.assert_array_equal(atm.z, sun_atm.z)

    def test_missing_radius_line_is_rejected(self, tmp_path, sun_mod_lines):
        lines = [l for l in sun_mod_lines if "adius" not in l]
        with pytest.raises(ValueError, match="cannot detect radius"):
            read_model_atmosphere(_write_mod(tmp_path, lines))

    def test_non_numeric_radius_is_rejected(self, tmp_path, sun_mod_lines):
        lines = list(sun_mod_lines)
        i = next(j for j, l in enumerate(lines) if "adius" in l)
        lines[i] = "  bogus radius value\n"
        with pytest.raises(ValueError, match="radius line is not a number"):
            read_model_atmosphere(_write_mod(tmp_path, lines))

    def test_missing_depth_point_count_is_rejected(self, tmp_path, sun_mod_lines):
        lines = [l for l in sun_mod_lines if "Number of depth points" not in l]
        with pytest.raises(ValueError, match="cannot find number of layers"):
            read_model_atmosphere(_write_mod(tmp_path, lines))

    def test_non_numeric_depth_point_count_is_rejected(self, tmp_path, sun_mod_lines):
        lines = list(sun_mod_lines)
        i = next(j for j, l in enumerate(lines) if "Number of depth points" in l)
        lines[i] = "  many Number of depth points\n"
        with pytest.raises(ValueError, match="cannot find number of layers"):
            read_model_atmosphere(_write_mod(tmp_path, lines))

    def test_missing_column_header_is_rejected(self, tmp_path, sun_mod_lines):
        lines = [l for l in sun_mod_lines if "lgTauR" not in l]
        with pytest.raises(ValueError, match="cannot find column header"):
            read_model_atmosphere(_write_mod(tmp_path, lines))

    def test_malformed_structure_row_is_rejected_not_skipped(self, tmp_path,
                                                             sun_mod_lines):
        """A truncated data row must fail loudly.

        Korg.jl parses these columns with no error handling, so a bad row is a
        hard failure there.  Skipping it silently would return an atmosphere
        with fewer layers than the header declares, and nothing downstream
        checks that.
        """
        lines = list(sun_mod_lines)
        header = next(j for j, l in enumerate(lines) if "lgTauR" in l)
        lines[header + 3] = "  4 -4.40 -4.3377   ****\n"
        with pytest.raises(ValueError, match="malformed model-structure row"):
            read_model_atmosphere(_write_mod(tmp_path, lines))

    def test_negative_pressures_are_clamped_to_zero(self, tmp_path, sun_mod_lines):
        """MARCS occasionally writes tiny negative pressures; Korg.jl zeroes them."""
        lines = list(sun_mod_lines)
        header = next(j for j, l in enumerate(lines) if "lgTauR" in l)
        row = lines[header + 1]
        lines[header + 1] = row[:38] + "-2.116E-02" + row[48:]
        atm = read_model_atmosphere(_write_mod(tmp_path, lines))
        assert atm.ne[0] == 0.0
        assert atm.n_total[0] > 0.0


