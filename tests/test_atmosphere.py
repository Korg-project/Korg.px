"""
Tests for ``korg.atmosphere`` — model atmosphere containers and file readers.

Four categories, matching the project's testing contract:

1. **Functional** — container properties, the planar/shell converters, the
   simple-atmosphere builder, and every error path of the MARCS and Phoenix
   readers (including malformed input).
2. **Agreement with Korg.jl** — the parsed structure of ``tests/data/sun.mod``
   and the shell geometry (``radii``, ``photosphere_correction``) are compared
   at machine precision against ``tests/synthesis_reference_data.json``,
   generated by ``tests/generate_synthesis_reference.jl``.  These quantities
   are pure arithmetic on file-parsed numbers, so they are exact — unlike a
   synthetic spectrum, which goes through the whole opacity stack.
3. **Autodiff** — ``ShellAtmosphere.photosphere_correction`` is differentiable
   with respect to the photospheric radius; the layer data are Python floats
   held in a list, so a traced *layer* provably cannot work and that is pinned.
4. **jit tracing** — the same split: geometry from a traced radius jits; the
   file readers cannot be traced and that is pinned.

Two bugs found while writing these tests are regression-pinned below; see
``TestReaderBugRegressions``.
"""

