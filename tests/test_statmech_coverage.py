class TestSahaIonWeights:

    def test_matches_julia(self, chem_ref, ionization_energies, partition_funcs):
        checked = 0
        for Z_str, cases in chem_ref["statmech"]["saha_ion_weights"].items():
            Z = int(Z_str)
            for key, ref in cases.items():
                T, ne = (float(x) for x in key.split("_"))
                try:
                    wII, wIII = S.saha_ion_weights(T, ne, Z, ionization_energies,
                                                   partition_funcs)
                except KeyError:
                    continue   # e.g. He III has no tabulated partition function
                assert float(wII) == pytest.approx(float(ref["wII"]), rel=1e-10), \
                    f"Z={Z} {key} wII"
                assert float(wIII) == pytest.approx(float(ref["wIII"]),
                                                    rel=1e-10, abs=1e-300), \
                    f"Z={Z} {key} wIII"
                checked += 1
        assert checked > 10, "reference data did not exercise saha_ion_weights"

    def test_hydrogen_takes_the_atom_equals_one_branch(self, ionization_energies,
                                                       partition_funcs):
        wII, wIII = S.saha_ion_weights(5778.0, 1e14, 1, ionization_energies,
                                       partition_funcs)
        assert wIII == 0.0
        assert float(wII) > 0.0

    def test_metals_take_the_else_branch(self, ionization_energies, partition_funcs):
        wII, wIII = S.saha_ion_weights(9000.0, 1e13, 26, ionization_energies,
                                       partition_funcs)
        assert float(wII) > 0.0 and float(wIII) > 0.0

    def test_missing_third_partition_function_raises(self, ionization_energies,
                                                     partition_funcs):
        """The ``else`` branch looks up ``Species(formula, 2)`` unguarded.

        Every element in the shipped table does have one, so this only bites a
        caller that supplies a partial dict — which ``korg.simple_ionization``
        anticipates with a ``try/except (KeyError, IndexError)``.  The batched
        ``_compute_saha_weights_jit`` avoids the issue differently, with a
        synthetic placeholder spline for H III.  Pin the divergence.
        """
        from korg.species import Species, Formula
        pruned = {k: v for k, v in partition_funcs.items()
                  if k != Species(Formula(2), 2)}
        with pytest.raises(KeyError):
            S.saha_ion_weights(9000.0, 1e13, 2, ionization_energies, pruned)
        # ... and with the full table it is fine
        wII, wIII = S.saha_ion_weights(9000.0, 1e13, 2, ionization_energies,
                                       partition_funcs)
        assert float(wII) > 0 and float(wIII) >= 0

    def test_zero_electron_density_is_clipped_not_divided_by_zero(
            self, ionization_energies, partition_funcs):
        wII, _ = S.saha_ion_weights(5778.0, 0.0, 1, ionization_energies,
                                    partition_funcs)
        assert np.isfinite(float(wII))
        assert float(wII) > 0.0

    def test_agrees_with_the_batched_jit_implementation(self, eq_data,
                                                        ionization_energies,
                                                        partition_funcs):
        """Two independent Saha routes: the dict-based one here and the vmapped
        ``_compute_saha_weights_jit`` used by the solver.  They differ in how the
        partition functions are evaluated (spline object vs padded knot arrays),
        so agreement is not free.
        """
        T, ne = 5778.0, 1e14
        wII_arr, wIII_arr = S._compute_saha_weights_jit(T, ne, eq_data)
        for Z in (1, 3, 6, 12, 20, 26):
            wII, wIII = S.saha_ion_weights(T, ne, Z, ionization_energies,
                                           partition_funcs)
            assert float(wII_arr[Z - 1]) == pytest.approx(float(wII), rel=1e-6), \
                f"wII mismatch for Z={Z}"
            assert float(wIII_arr[Z - 1]) == pytest.approx(float(wIII), rel=1e-6,
                                                           abs=1e-300), \
                f"wIII mismatch for Z={Z}"


class TestGetLogNK:

    def test_matches_julia(self, chem_ref, log_K):
        from korg.species import Species
        checked = 0
        for mol_str, cases in chem_ref["statmech"]["get_log_nK"].items():
            mol = Species(mol_str)
            if mol not in log_K:
                continue
            for T_str, ref in cases.items():
                got = float(S.get_log_nK(mol, float(T_str), log_K))
                assert got == pytest.approx(float(ref), rel=1e-10), f"{mol_str} {T_str}"
                checked += 1
        assert checked > 5

    def test_polyatomic_conversion_uses_n_atoms_minus_one(self, log_K):
        """log nK = log Kp − (n_atoms − 1) log10(kT)."""
        from korg.species import Species
        from korg.constants import kboltz_cgs
        T = 5000.0
        for mol_str in ("H2", "H2O"):
            mol = Species(mol_str)
            if mol not in log_K:
                continue
            log_Kp = float(log_K[mol](np.log(T)))
            expected = log_Kp - (mol.n_atoms() - 1) * np.log10(kboltz_cgs * T)
            assert float(S.get_log_nK(mol, T, log_K)) == pytest.approx(expected,
                                                                       rel=1e-13)


