"""
Bounds checking for continuum absorption, and the four sources Korg.jl wraps.

Korg.jl v1.2.1 wraps ``Hminus_bf``, ``Hminus_ff``, ``H2plus_bf_and_ff`` and
``Heminus_ff`` in ``bounds_checked_absorption``, which returns *exactly zero*
outside the range each underlying table is valid over.  Korg.px used to
extrapolate instead — off the end of a bilinear interpolant, with no error
control and no comment saying it was intended.  These tests pin the adopted
Julia behaviour against freshly generated references.

Four categories, matching the project's test taxonomy:

1. Functional — bounds in both directions, the ``error_oobounds`` flag,
   exactly-on-boundary inputs, degenerate inputs.
2. High-precision agreement with Korg.jl (``tests/chemistry_reference_data.json``,
   generated by ``tests/generate_chemistry_reference.jl``).
3. Autodiff — ``jax.grad`` finite and matching central differences.
4. jit-tracing — what traces, and what provably cannot.
"""

import json
import os

import jax
import jax.numpy as jnp
import numpy as np
import pytest

import korg  # noqa: F401 — side effect: enables x64
from korg import continuum as C
from korg.constants import c_cgs
from korg.continuum_absorption import bounds_checking as B
from korg.continuum_absorption.bounds_checking import (
    Interval, closed_interval, contained, contained_slice, lambda_to_nu_bound,
    bounds_checked_absorption, in_bounds_mask, clamp_to_bound,
    HMINUS_BF_NU_BOUND, HMINUS_BF_TEMP_BOUND,
    HMINUS_FF_NU_BOUND, HMINUS_FF_TEMP_BOUND,
    H2PLUS_NU_BOUND, H2PLUS_TEMP_BOUND,
    HEMINUS_FF_NU_BOUND, HEMINUS_FF_TEMP_BOUND,
)

REFERENCE_FILE = os.path.join(os.path.dirname(__file__), "chemistry_reference_data.json")
JULIA_REFERENCE_FILE = os.path.join(os.path.dirname(__file__), "julia_reference_data.json")


def _load(path):
    if not os.path.exists(path):
        return {}
    with open(path) as f:
        return json.load(f)


@pytest.fixture(scope="module")
def chem_ref():
    data = _load(REFERENCE_FILE)
    if not data:
        pytest.skip("chemistry_reference_data.json missing; "
                    "run tests/generate_chemistry_reference.jl")
    return data


@pytest.fixture(scope="module")
def julia_ref():
    return _load(JULIA_REFERENCE_FILE)


def nu_of_A(lambda_A):
    """Frequency (Hz) of a wavelength given in Å, matching the Julia generator."""
    return c_cgs / (lambda_A * 1e-8)


def _as_float(x):
    """JSON round-trip helper: the generator stringifies Inf/NaN."""
    return float(x)


