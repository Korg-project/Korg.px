class TestIntervalPrimitives:
    """Interval algebra, exclusive vs closed, and the λ→ν conversion."""

    def test_interval_is_exclusive_by_default(self):
        iv = Interval(3.0, 10.0)
        assert contained(5.0, iv)
        assert not contained(3.0, iv)
        assert not contained(10.0, iv)

    def test_closed_interval_admits_its_endpoints(self):
        iv = closed_interval(3.0, 10.0)
        assert contained(3.0, iv)
        assert contained(10.0, iv)
        assert contained(5.0, iv)
        assert not contained(2.0, iv)
        assert not contained(11.0, iv)

    def test_closed_interval_nudges_outward_by_one_ulp(self):
        """closed_interval widens by one ULP; that is *how* it becomes inclusive."""
        iv = closed_interval(1400.0, 10080.0)
        assert iv.lower < 1400.0
        assert iv.upper > 10080.0
        assert iv.lower == np.nextafter(1400.0, -np.inf)
        assert iv.upper == np.nextafter(10080.0, np.inf)

    def test_interval_rejects_inverted_bounds(self):
        with pytest.raises(ValueError, match="upper bound must exceed"):
            Interval(10.0, 3.0)
        with pytest.raises(ValueError):
            Interval(5.0, 5.0)

    def test_infinite_endpoints_are_not_nudged(self):
        iv = closed_interval(0.0, np.inf)
        assert iv.upper == np.inf
        assert contained(1e300, iv)
        assert not contained(np.inf, iv)

    @pytest.mark.parametrize("vals,lo,hi,expected", [
        ([1.0, 2.0, 4.0, 5.0, 6.0, 8.0, 9.0, 12.0], 3.0, 10.0, [4.0, 5.0, 6.0, 8.0, 9.0]),
        # every value below the interval
        ([1.0, 2.0, 3.0], 10.0, 20.0, []),
        # every value above the interval
        ([100.0, 200.0], 10.0, 20.0, []),
        # everything inside
        ([11.0, 12.0], 10.0, 20.0, [11.0, 12.0]),
    ])
    def test_contained_slice(self, vals, lo, hi, expected):
        sl = contained_slice(np.array(vals), closed_interval(lo, hi))
        assert isinstance(sl, slice)
        assert list(np.array(vals)[sl]) == expected

    def test_contained_slice_is_inclusive_of_endpoints(self):
        """searchsortedfirst..searchsortedlast admits values sitting on the bound.

        This asymmetry (ν inclusive, T exclusive) is Korg's, and it matters: see
        test_hminus_ff_lower_nu_bound_is_inclusive.
        """
        vals = np.array([1.0, 3.0, 5.0, 10.0, 12.0])
        sl = contained_slice(vals, Interval(3.0, 10.0))
        assert list(vals[sl]) == [3.0, 5.0, 10.0]

    def test_contained_slice_empty_input(self):
        sl = contained_slice(np.array([]), closed_interval(1.0, 2.0))
        assert sl == slice(0, 0)

    def test_lambda_to_nu_bound_reverses_the_interval(self):
        nu_b = lambda_to_nu_bound(closed_interval(1823e-8, 151890e-8))
        # short λ ↔ high ν
        assert nu_b.lower < nu_of_A(151890.0) * 1.001
        assert nu_b.upper > nu_of_A(1823.0) * 0.999
        assert nu_b.lower < nu_b.upper

    def test_lambda_to_nu_bound_handles_zero_wavelength(self):
        """λ = 0 maps to ν = ∞ without dividing by zero."""
        nu_b = lambda_to_nu_bound(Interval(0.0, 1e-3))
        assert np.isinf(nu_b.upper)
        assert np.isfinite(nu_b.lower)


