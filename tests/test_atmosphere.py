def _planar_layers(n=4):
    return [
        PlanarAtmosphereLayer(
            tau_ref=10.0 ** (i - 2),
            z=1e8 * (n - i),
            temperature=4000.0 + 500.0 * i,
            electron_number_density=1e11 * (i + 1),
            number_density=1e16 * (i + 1),
        )
        for i in range(n)
    ]


