class TestCreateSimpleAtmosphere:

    def test_mismatched_lengths_are_rejected(self):
        with pytest.raises(ValueError, match="same length"):
            create_simple_atmosphere([5000.0, 6000.0], [-1.0])

    def test_planar_is_the_default(self):
        atm = create_simple_atmosphere(np.linspace(8000, 4000, 12),
                                       np.linspace(-4, 2, 12))
        assert isinstance(atm, PlanarAtmosphere)
        assert atm.n_layers == 12
        assert np.all(np.isfinite(atm.z))
        assert np.all(atm.ne > 0)
        assert np.all(atm.n_total > 0)

    def test_spherical_flag_returns_a_shell(self):
        atm = create_simple_atmosphere(np.linspace(8000, 4000, 12),
                                       np.linspace(-4, 2, 12), spherical=True)
        assert isinstance(atm, ShellAtmosphere)
        assert atm.R_photosphere > 0
        np.testing.assert_allclose(atm.r, atm.R_photosphere + atm.z, rtol=0)

    def test_reference_wavelength_is_passed_through(self):
        atm = create_simple_atmosphere([5000.0], [0.0], reference_wavelength=1.2e-4)
        assert atm.reference_wavelength == 1.2e-4

    def test_ne_falls_back_when_the_saha_discriminant_underflows(self):
        """At 100 K the Boltzmann factor underflows to exactly zero.

        The Saha quadratic then has ``b == c == 0``, so ``discriminant == 0``
        and the function takes its ``ne = 0.1 n_total`` fallback branch.  This
        is the only way to reach that branch.
        """
        atm = create_simple_atmosphere([100.0, 100.0], [-1.0, 0.0])
        np.testing.assert_allclose(atm.ne, 0.1 * atm.n_total, rtol=1e-15)

    def test_logg_changes_the_height_scale(self):
        T = np.linspace(8000, 4000, 12)
        lt = np.linspace(-4, 2, 12)
        thin = create_simple_atmosphere(T, lt, logg=5.0)
        thick = create_simple_atmosphere(T, lt, logg=3.0)
        assert np.ptp(thick.z) > np.ptp(thin.z)


