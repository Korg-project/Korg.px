class TestBoundConstantsMatchJulia:
    """The bound endpoints must be bit-identical, not merely close.

    They are computed by a fixed-point ULP walk (``_convert_lambda_endpoint``),
    so a one-bit difference flips the answer at a table edge from the correct
    value to exactly zero.
    """

    NAMES = {
        "Hminus_bf_nu": HMINUS_BF_NU_BOUND,
        "Hminus_bf_temp": HMINUS_BF_TEMP_BOUND,
        "Hminus_ff_nu": HMINUS_FF_NU_BOUND,
        "Hminus_ff_temp": HMINUS_FF_TEMP_BOUND,
        "H2plus_nu": H2PLUS_NU_BOUND,
        "H2plus_temp": H2PLUS_TEMP_BOUND,
        "Heminus_ff_nu": HEMINUS_FF_NU_BOUND,
        "Heminus_ff_temp": HEMINUS_FF_TEMP_BOUND,
    }

    @pytest.mark.parametrize("name", sorted(NAMES))
    def test_endpoints_bit_identical(self, chem_ref, name):
        ref = chem_ref["bounds"]["intervals"][name]
        iv = self.NAMES[name]
        assert float(iv.lower) == _as_float(ref["lower"]), f"{name}.lower"
        assert float(iv.upper) == _as_float(ref["upper"]), f"{name}.upper"

    def test_contained_matches_julia_at_every_probe(self, chem_ref):
        probe_to_interval = {
            "Hminus_ff_nu": HMINUS_FF_NU_BOUND,
            "Heminus_ff_nu": HEMINUS_FF_NU_BOUND,
            "H2plus_nu": H2PLUS_NU_BOUND,
            "Hminus_bf_nu": HMINUS_BF_NU_BOUND,
            "Hminus_ff_temp": HMINUS_FF_TEMP_BOUND,
            "H2plus_temp": H2PLUS_TEMP_BOUND,
            "unbounded_temp": Interval(0, np.inf),
        }
        for name, cases in chem_ref["bounds"]["contained"].items():
            iv = probe_to_interval[name]
            for value_str, expected in cases.items():
                got = bool(contained(float(value_str), iv))
                assert got == expected, (
                    f"{name}: contained({value_str}) = {got}, Julia says {expected}")

    def test_contained_slice_matches_julia(self, chem_ref):
        ref = chem_ref["bounds"]["contained_slice"]
        vals = np.array([_as_float(v) for v in ref["values"]])
        sl = contained_slice(vals, HMINUS_FF_NU_BOUND)
        # Julia reports 1-based inclusive indices
        assert sl.start == ref["first"] - 1
        assert sl.stop == ref["last"]
        np.testing.assert_array_equal(vals[sl],
                                      [_as_float(v) for v in ref["selected"]])


class TestContinuumSourcesMatchJuliaOutOfBounds:
    """Each source across 14 temperatures × 15 wavelengths, in and out of bounds.

    ``rtol=1e-13`` — these are deterministic table lookups; the observed
    disagreement is a few ULP.
    """

    RTOL = 1e-13

    def _cases(self, chem_ref, source):
        ob = chem_ref["continuum_oob"]
        for key, ref in ob["outputs"][source].items():
            T, lam = (float(x) for x in key.split("_"))
            yield key, T, lam, _as_float(ref)

    def test_Hminus_ff(self, chem_ref):
        inp = chem_ref["continuum_oob"]["inputs"]
        n_zero = n_pos = 0
        for key, T, lam, ref in self._cases(chem_ref, "Hminus_ff"):
            got = float(C.Hminus_ff(nu_of_A(lam), T, inp["nH_I_div_U"], inp["ne"]))
            if ref == 0.0:
                assert got == 0.0, f"{key}: Julia returns exactly 0, got {got}"
                n_zero += 1
            else:
                assert got == pytest.approx(ref, rel=self.RTOL), key
                n_pos += 1
        assert n_zero > 0 and n_pos > 0

    def test_Heminus_ff(self, chem_ref):
        inp = chem_ref["continuum_oob"]["inputs"]
        n_zero = n_pos = 0
        for key, T, lam, ref in self._cases(chem_ref, "Heminus_ff"):
            got = float(C.Heminus_ff(nu_of_A(lam), T, inp["nHe_I_div_U"], inp["ne"]))
            if ref == 0.0:
                assert got == 0.0, f"{key}: Julia returns exactly 0, got {got}"
                n_zero += 1
            else:
                assert got == pytest.approx(ref, rel=self.RTOL), key
                n_pos += 1
        assert n_zero > 0 and n_pos > 0

    def test_H2plus_bf_and_ff(self, chem_ref):
        inp = chem_ref["continuum_oob"]["inputs"]
        n_zero = n_pos = 0
        for key, T, lam, ref in self._cases(chem_ref, "H2plus_bf_and_ff"):
            got = float(C.H2plus_bf_and_ff(nu_of_A(lam), T, inp["nH_I"], inp["nH_II"]))
            if ref == 0.0:
                assert got == 0.0, f"{key}: Julia returns exactly 0, got {got}"
                n_zero += 1
            else:
                assert got == pytest.approx(ref, rel=self.RTOL), key
                n_pos += 1
        assert n_zero > 0 and n_pos > 0

    def test_Hminus_bf_per_unit_density(self, chem_ref):
        """Korg v1.2 passes n(H⁻) from chemical equilibrium; Korg.px derives it
        from n(H I, n=1) via Saha (the v1.1 convention).  Divide out the density
        so this compares the McLaughlin cross section, the stimulated-emission
        factor and the bounds — not the density convention.
        """
        inp = chem_ref["continuum_oob"]["inputs"]
        n_zero = n_pos = 0
        for key, T, lam, ref in self._cases(chem_ref, "Hminus_bf"):
            nu = nu_of_A(lam)
            per_ion = float(C.Hminus_bf(nu, T, 1.0, inp["ne"])
                            / C.ndens_Hminus(1.0, inp["ne"], T))
            got = per_ion * inp["n_Hminus"]
            if ref == 0.0:
                assert got == 0.0, f"{key}: Julia returns exactly 0, got {got}"
                n_zero += 1
            else:
                assert got == pytest.approx(ref, rel=self.RTOL), key
                n_pos += 1
        assert n_zero > 0 and n_pos > 0


class TestKnownDivergencesArePinned:
    """The divergences we chose to keep, asserted so they cannot drift silently."""

    def test_hminus_density_convention_differs_by_exactly_two_over_U(self, julia_ref):
        """Korg v1.2 folds U(H I) = 2 into its H⁻ coefficient; Korg.px divides by
        the actual partition function.  The ratio is exactly 2/U(H I)."""
        if "continuum_sources" not in julia_ref:
            pytest.skip("continuum_sources fixture missing")
        for label, block in julia_ref["continuum_sources"].items():
            ratio = block["nHminus_ground_state"] / block["nHminus_korg_v1_2"]
            expected = 2.0 / block["U_H_I"]
            assert ratio == pytest.approx(expected, rel=1e-13), label

    def test_H2plus_raw_kernel_reproduces_the_unwrapped_julia_fixture(self, julia_ref):
        """`julia_reference_data.json` was generated from Julia's *unwrapped*
        ``_H2plus_bf_and_ff``, which extrapolates below 3150 K and returns a
        negative absorption coefficient there.  Korg.px keeps that kernel under
        the same private name so the fixture stays meaningful, and exposes only
        the bounds-checked version publicly.

        Note the existing test in test_julia_reference.py compares these with
        ``np.isclose``'s default ``atol=1e-8``, which is larger than every value
        in the fixture — so it cannot actually detect a disagreement.  This one
        uses atol=0.
        """
        if "H2plus_bf_and_ff" not in julia_ref:
            pytest.skip("H2plus_bf_and_ff fixture missing")
        ref = julia_ref["H2plus_bf_and_ff"]
        inp = ref["inputs"]
        nu = nu_of_A(inp["temperature_test_wavelength_angstrom"])

        saw_negative = False
        for T_str, julia_val in ref["temperature_outputs"].items():
            T = float(T_str)
            raw = float(C._H2plus_bf_and_ff(nu, T, inp["nH_I"], inp["nH_II"]))
            assert raw == pytest.approx(julia_val, rel=1e-10, abs=0.0), f"T={T}"
            if julia_val < 0:
                saw_negative = True
                # ... and the public entry point refuses to return it
                assert float(C.H2plus_bf_and_ff(nu, T, inp["nH_I"], inp["nH_II"])) == 0.0
        assert saw_negative, "fixture no longer exercises the extrapolated region"

    def test_hminus_ff_lower_nu_bound_is_inclusive(self):
        """ν = c/(151890·1e-8) lands *exactly* on ``HMINUS_FF_NU_BOUND.lower``.

        ``contained`` (exclusive) would reject it; Korg's wrapper selects
        frequencies with ``contained_slice`` (inclusive), so it is in bounds and
        returns a finite value.  Getting this wrong silently zeroes the reddest
        point of the Bell & Berrington table.
        """
        nu = nu_of_A(151890.0)
        assert nu == HMINUS_FF_NU_BOUND.lower
        assert not contained(nu, HMINUS_FF_NU_BOUND)
        assert bool(in_bounds_mask(nu, 5000.0, HMINUS_FF_NU_BOUND, HMINUS_FF_TEMP_BOUND))
