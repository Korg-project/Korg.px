PHOENIX_TAU = np.array([0.0, 1e-4, 1e-2, 1.0, 10.0])
PHOENIX_TEMP = np.array([3500.0, 3600.0, 3800.0, 4200.0, 5000.0])
PHOENIX_PGAS = np.array([1e2, 1e3, 1e4, 1e5, 1e6])
PHOENIX_PE = np.array([1e-2, 1e-1, 1.0, 10.0, 100.0])


def _install_fits_stub(monkeypatch, teff=5800.0, include_teff=True,
                       tau=PHOENIX_TAU, temp=PHOENIX_TEMP,
                       pgas=PHOENIX_PGAS, pe=PHOENIX_PE):
    """Install a minimal stand-in for ``astropy.io.fits``.

    ``astropy`` is not installed in this project's virtualenv (the system copy
    is built against NumPy 1.x and raises ``AttributeError: np.in1d`` on
    import), so a real Phoenix FITS file cannot be round-tripped here.  The
    stub reproduces exactly the four calls the reader makes —
    ``fits.open`` as a context manager, ``hdul[0].header.get``,
    ``hdul[1].data`` and ``column.astype(float)`` — so every statement of
    ``_read_phoenix_model_atmosphere`` still executes against real arrays.
    What is *not* covered is astropy's own FITS decoding, which is astropy's
    responsibility rather than Korg's.
    """
    import sys
    import types

    class _HDU:
        def __init__(self, header=None, data=None):
            self.header = header if header is not None else {}
            self.data = data

    class _HDUList(list):
        def __enter__(self):
            return self

        def __exit__(self, *exc):
            return False

    header = {"PHXTEFF": teff} if include_teff else {}
    table = {"tau": np.asarray(tau), "temp": np.asarray(temp),
             "pgas": np.asarray(pgas), "pe": np.asarray(pe)}

    fits_mod = types.ModuleType("astropy.io.fits")
    fits_mod.open = lambda fname: _HDUList([_HDU(header=header), _HDU(data=table)])

    io_mod = types.ModuleType("astropy.io")
    io_mod.fits = fits_mod
    astropy_mod = types.ModuleType("astropy")
    astropy_mod.io = io_mod

    monkeypatch.setitem(sys.modules, "astropy", astropy_mod)
    monkeypatch.setitem(sys.modules, "astropy.io", io_mod)
    monkeypatch.setitem(sys.modules, "astropy.io.fits", fits_mod)


