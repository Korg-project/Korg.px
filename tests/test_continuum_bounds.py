def _central_difference(f, x, rel_step=1e-6):
    h = abs(x) * rel_step
    return (f(x + h) - f(x - h)) / (2 * h)


class TestAutodiff:
    """grad must be finite everywhere, and match finite differences in bounds."""

    SOURCES = {
        "Hminus_bf": lambda nu, T: C.Hminus_bf(nu, T, 1e16, 1e13),
        "Hminus_ff": lambda nu, T: C.Hminus_ff(nu, T, 1e16, 1e13),
        "Heminus_ff": lambda nu, T: C.Heminus_ff(nu, T, 1e15, 1e13),
        "H2plus_bf_and_ff": lambda nu, T: C.H2plus_bf_and_ff(nu, T, 1e17, 1e12),
    }

    @pytest.mark.parametrize("name", sorted(SOURCES))
    def test_grad_matches_finite_difference_in_bounds(self, name):
        f = self.SOURCES[name]
        nu, T = nu_of_A(8000.0), 5778.0

        gT = float(jax.grad(lambda t: f(nu, t))(T))
        fdT = _central_difference(lambda t: float(f(nu, t)), T)
        assert gT == pytest.approx(fdT, rel=1e-5), f"{name}: d/dT"

        gnu = float(jax.grad(lambda n: f(n, T))(nu))
        fdnu = _central_difference(lambda n: float(f(n, T)), nu)
        assert gnu == pytest.approx(fdnu, rel=1e-5), f"{name}: d/dν"

        assert gT != 0.0 and gnu != 0.0, f"{name}: gradient is identically zero"

    @pytest.mark.parametrize("name", sorted(SOURCES))
    @pytest.mark.parametrize("lam,T,label", [
        (8000.0, 12000.0, "T above the table"),
        (8000.0, 500.0, "T below the table"),
        (300000.0, 5778.0, "λ above the table"),
        (100.0, 5778.0, "λ below the table"),
        (8000.0, 0.0, "T = 0 (degenerate)"),
    ])
    def test_grad_is_finite_out_of_bounds(self, name, lam, T, label):
        """A masked branch must not leak a NaN cotangent.

        ``jnp.where(mask, value, 0.0)`` hides a NaN *value* but reverse mode still
        multiplies the discarded branch's derivative by zero — and 0 * NaN is NaN.
        The fix is ``clamp_to_bound``, which folds out-of-bounds inputs onto a
        strictly positive stand-in before any log/sqrt/division.
        """
        f = self.SOURCES[name]
        nu = nu_of_A(lam)
        gT = float(jax.grad(lambda t: f(nu, t))(T))
        gnu = float(jax.grad(lambda n: f(n, T))(nu))
        assert np.isfinite(gT), f"{name} @ {label}: d/dT = {gT}"
        assert np.isfinite(gnu), f"{name} @ {label}: d/dν = {gnu}"

    def test_grad_wrt_densities_is_exact(self):
        """All four sources are linear in their density arguments."""
        nu, T = nu_of_A(8000.0), 5778.0
        g = float(jax.grad(lambda n: C.Hminus_ff(nu, T, n, 1e13))(1e16))
        assert g == pytest.approx(float(C.Hminus_ff(nu, T, 1.0, 1e13)), rel=1e-12)
        g = float(jax.grad(lambda n: C.Heminus_ff(nu, T, 1e15, n))(1e13))
        assert g == pytest.approx(float(C.Heminus_ff(nu, T, 1e15, 1.0)), rel=1e-12)

    def test_grad_of_total_continuum_is_finite(self, julia_ref):
        if "continuum_sources" not in julia_ref:
            pytest.skip("continuum_sources fixture missing")
        block = julia_ref["continuum_sources"]["solar"]
        from korg.species import Species
        nd = {Species(k.replace("_", " ")): v
              for k, v in block["number_densities"].items()}
        pf = {"H_I": lambda x: block["U_H_I"], "He_I": lambda x: block["U_He_I"]}
        nu = jnp.array([nu_of_A(5000.0), nu_of_A(8000.0)])

        def total(T):
            return jnp.sum(C.total_continuum_absorption(nu, T, block["ne"], nd, pf))

        g = float(jax.grad(total)(block["T"]))
        assert np.isfinite(g) and g != 0.0

    def test_electron_scattering_grad(self):
        g = float(jax.grad(C.electron_scattering)(1e13))
        assert g == pytest.approx(float(C.electron_scattering(1.0)), rel=1e-13)

    def test_rayleigh_grad_is_finite(self):
        g = jax.grad(lambda nu: C.rayleigh(nu, 1e17, 1e16, 1e12))(nu_of_A(5000.0))
        assert np.isfinite(float(g)) and float(g) != 0.0


