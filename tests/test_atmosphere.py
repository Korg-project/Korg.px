class TestPlanarAtmosphereContainer:

    def test_length_and_n_layers_agree(self):
        atm = PlanarAtmosphere(_planar_layers(7))
        assert len(atm) == 7
        assert atm.n_layers == 7

    def test_column_properties_are_layerwise(self):
        layers = _planar_layers(3)
        atm = PlanarAtmosphere(layers)
        np.testing.assert_array_equal(atm.tau_ref, [l.tau_ref for l in layers])
        np.testing.assert_array_equal(atm.z, [l.z for l in layers])
        np.testing.assert_array_equal(atm.T, [l.temperature for l in layers])
        np.testing.assert_array_equal(
            atm.ne, [l.electron_number_density for l in layers])
        np.testing.assert_array_equal(
            atm.n_total, [l.number_density for l in layers])

    def test_log_tau_ref_is_log10_of_tau_ref(self):
        atm = PlanarAtmosphere(_planar_layers(5))
        np.testing.assert_allclose(atm.log_tau_ref, np.log10(atm.tau_ref),
                                   rtol=0, atol=0)

    def test_default_reference_wavelength_is_5000_angstrom(self):
        assert PlanarAtmosphere(_planar_layers()).reference_wavelength == 5e-5

    def test_repr_reports_the_layer_count(self):
        assert repr(PlanarAtmosphere(_planar_layers(9))) == \
            "PlanarAtmosphere with 9 layers"


class TestShellAtmosphereContainer:

    def test_length_and_n_layers_agree(self):
        atm = ShellAtmosphere(_shell_layers(6), R_photosphere=3e10)
        assert len(atm) == 6
        assert atm.n_layers == 6

    def test_column_properties_are_layerwise(self):
        layers = _shell_layers(3)
        atm = ShellAtmosphere(layers, R_photosphere=3e10)
        np.testing.assert_array_equal(atm.tau_ref, [l.tau_ref for l in layers])
        np.testing.assert_array_equal(atm.z, [l.z for l in layers])
        np.testing.assert_array_equal(atm.T, [l.temperature for l in layers])
        np.testing.assert_array_equal(
            atm.ne, [l.electron_number_density for l in layers])
        np.testing.assert_array_equal(
            atm.n_total, [l.number_density for l in layers])
        np.testing.assert_allclose(atm.log_tau_ref, np.log10(atm.tau_ref),
                                   rtol=0, atol=0)

    def test_r_is_R_photosphere_plus_z(self):
        """Korg.jl: ``radii = [atm.R + l.z for l in atm.layers]``.

        ``ShellAtmosphere`` had no ``r`` at all before this change, so both
        ``synthesis.py`` and ``synthesis_preparation.py`` raised
        ``AttributeError`` the moment a shell atmosphere was passed in.
        """
        atm = ShellAtmosphere(_shell_layers(4), R_photosphere=3e10)
        np.testing.assert_allclose(atm.r, 3e10 + atm.z, rtol=0, atol=0)

    def test_photosphere_correction_uses_the_outermost_layer(self):
        """Korg.jl: ``photosphere_correction = radii[1]^2 / atm.R^2`` (1-based)."""
        atm = ShellAtmosphere(_shell_layers(4), R_photosphere=3e10)
        assert atm.photosphere_correction == pytest.approx(
            (atm.r[0] / 3e10) ** 2, rel=0, abs=0)

    def test_photosphere_correction_is_one_when_the_top_layer_is_the_photosphere(self):
        layers = _shell_layers(3)
        layers[0].z = 0.0
        atm = ShellAtmosphere(layers, R_photosphere=7e10)
        assert atm.photosphere_correction == 1.0

    def test_repr_reports_layers_and_radius(self):
        atm = ShellAtmosphere(_shell_layers(5), R_photosphere=3e10)
        assert repr(atm) == "ShellAtmosphere with 5 layers, R=3.00e+10 cm"


class TestAtmosphereConverters:
    """``ShellAtmosphere.from_planar`` / ``PlanarAtmosphere.from_shell``.

    Ports of Korg.jl's ``ShellAtmosphere(atm::PlanarAtmosphere, R)`` and
    ``PlanarAtmosphere(atm::ShellAtmosphere)``.
    """

    def test_from_planar_copies_the_layer_data_bit_for_bit(self):
        planar = PlanarAtmosphere(_planar_layers(5), reference_wavelength=1.2e-4)
        shell = ShellAtmosphere.from_planar(planar, 3e10)
        assert isinstance(shell, ShellAtmosphere)
        assert shell.R_photosphere == 3e10
        assert shell.reference_wavelength == 1.2e-4
        for name in ("tau_ref", "z", "T", "ne", "n_total"):
            np.testing.assert_array_equal(getattr(shell, name),
                                          getattr(planar, name))

    def test_from_shell_discards_only_the_radius(self):
        shell = ShellAtmosphere(_shell_layers(5), 3e10, reference_wavelength=1.2e-4)
        planar = PlanarAtmosphere.from_shell(shell)
        assert isinstance(planar, PlanarAtmosphere)
        assert planar.reference_wavelength == 1.2e-4
        for name in ("tau_ref", "z", "T", "ne", "n_total"):
            np.testing.assert_array_equal(getattr(planar, name),
                                          getattr(shell, name))

    def test_round_trip_is_the_identity_on_layer_data(self, sun_atm):
        back = PlanarAtmosphere.from_shell(ShellAtmosphere.from_planar(sun_atm, 3e10))
        for name in ("tau_ref", "z", "T", "ne", "n_total"):
            np.testing.assert_array_equal(getattr(back, name),
                                          getattr(sun_atm, name))


