"""
Coverage and correctness tests for :mod:`korg.statmech`.

Complements ``test_chemical_equilibrium_jit.py`` (which pins the batched Newton
solver against ``tests/reference_chemical_equilibrium.py``) and
``test_statmech_extended_reference.py`` (Saha / log nK physics), by exercising
the parts neither touches: the occupation-probability formalism, the precompute
machinery, the Picard path, the per-layer drivers, and the differentiability
asymmetry between the two solvers.

Four categories:

1. Functional — branch selectors (``use_hubeny_generalization``, ``atom == 1``,
   zero-molecule data), error paths, degenerate inputs.
2. High-precision agreement with Korg.jl, from
   ``tests/chemistry_reference_data.json`` (generated by
   ``tests/generate_chemistry_reference.jl``).
3. Autodiff — the batched solver is reverse-mode differentiable through an
   implicit-function-theorem ``custom_jvp``; ``picard_chemical_equilibrium_guess``
   is forward-mode only because it uses ``lax.while_loop``.  Both are asserted.
4. jit-tracing — what traces and what provably cannot.
"""

