class TestAutodiff:

    def test_photosphere_correction_grad_matches_finite_differences(self):
        layers = _shell_layers(4)
        R0 = 3.0e10

        def f(R):
            return ShellAtmosphere(layers, R).photosphere_correction

        g = jax.grad(f)(R0)
        h = R0 * 1e-6
        fd = (f(R0 + h) - f(R0 - h)) / (2 * h)
        assert np.isfinite(g)
        assert g != 0.0
        assert g == pytest.approx(fd, rel=1e-5)

    def test_photosphere_correction_grad_has_the_analytic_value(self):
        """d/dR (1 + z0/R)² = -2 z0 (R + z0) / R³."""
        layers = _shell_layers(4)
        z0 = layers[0].z
        R0 = 3.0e10
        g = jax.grad(lambda R: ShellAtmosphere(layers, R).photosphere_correction)(R0)
        assert g == pytest.approx(-2.0 * z0 * (R0 + z0) / R0 ** 3, rel=1e-12)

    def test_radius_grad_wrt_R_is_one_everywhere(self):
        layers = _shell_layers(4)
        g = jax.jacfwd(lambda R: ShellAtmosphere(layers, R).r)(3.0e10)
        np.testing.assert_allclose(np.asarray(g), np.ones(4), rtol=1e-14)

    def test_a_traced_layer_provably_cannot_work(self):
        """Layer data live in a Python list that is turned into ``np.array``.

        ``np.array`` of a JAX tracer is not differentiable and never can be
        without restructuring the container, so this is pinned rather than
        left ambiguous.
        """
        def f(z):
            layer = ShellAtmosphereLayer(1e-4, z, 4000.0, 1e12, 1e16)
            return ShellAtmosphere([layer], 3e10).r[0]

        with pytest.raises(jax.errors.TracerArrayConversionError):
            jax.grad(f)(1e8)


