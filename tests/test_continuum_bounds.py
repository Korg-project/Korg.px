def _kernel(nu, T, scale=1.0):
    """Trivial absorption kernel: linear in ν so truncation is easy to see."""
    return scale * nu * T


class TestBoundsCheckedAbsorption:
    """Julia's NumPy-side wrapper: truncation, error_oobounds, out_alpha."""

    NU_BOUND = closed_interval(10.0, 100.0)
    T_BOUND = closed_interval(1000.0, 2000.0)

    def _wrapped(self):
        return bounds_checked_absorption(_kernel, nu_bound=self.NU_BOUND,
                                         temp_bound=self.T_BOUND)

    def test_all_in_bounds(self):
        f = self._wrapped()
        nus = np.array([20.0, 50.0, 90.0])
        out = f(nus, 1500.0)
        np.testing.assert_allclose(out, nus * 1500.0, rtol=0, atol=0)

    def test_truncates_below_and_above(self):
        f = self._wrapped()
        nus = np.array([1.0, 5.0, 20.0, 50.0, 500.0, 900.0])
        out = f(nus, 1500.0)
        assert out[0] == 0.0 and out[1] == 0.0      # below ν_bound
        assert out[4] == 0.0 and out[5] == 0.0      # above ν_bound
        np.testing.assert_allclose(out[2:4], nus[2:4] * 1500.0)

    def test_temperature_out_of_bounds_zeroes_everything(self):
        f = self._wrapped()
        nus = np.array([20.0, 50.0, 90.0])
        for T in (999.0, 2001.0, 0.0):
            np.testing.assert_array_equal(f(nus, T), np.zeros(3))

    def test_exactly_on_the_boundary_is_in_bounds(self):
        f = self._wrapped()
        nus = np.array([10.0, 100.0])
        for T in (1000.0, 2000.0):
            out = f(nus, T)
            assert np.all(out > 0), f"endpoint rejected at T={T}"

    def test_error_oobounds_raises_for_temperature(self):
        f = self._wrapped()
        with pytest.raises(ValueError, match="invalid temperature"):
            f(np.array([20.0, 50.0]), 5000.0, error_oobounds=True)

    def test_error_oobounds_raises_for_frequency(self):
        f = self._wrapped()
        with pytest.raises(ValueError, match="invalid frequency"):
            f(np.array([1.0, 20.0, 50.0]), 1500.0, error_oobounds=True)
        with pytest.raises(ValueError, match="invalid frequency"):
            f(np.array([20.0, 50.0, 5000.0]), 1500.0, error_oobounds=True)

    def test_error_oobounds_silent_when_everything_is_in_bounds(self):
        f = self._wrapped()
        out = f(np.array([20.0, 50.0]), 1500.0, error_oobounds=True)
        assert np.all(out > 0)

    def test_out_alpha_accumulates_in_place(self):
        f = self._wrapped()
        nus = np.array([20.0, 50.0])
        acc = np.ones(2, dtype=np.float64)
        ret = f(nus, 1500.0, out_alpha=acc)
        assert ret is acc, "must accumulate in place, like Julia's out_α"
        np.testing.assert_allclose(acc, 1.0 + nus * 1500.0)

    def test_out_alpha_length_mismatch_is_rejected(self):
        f = self._wrapped()
        with pytest.raises(AssertionError, match="same length"):
            f(np.array([20.0, 50.0]), 1500.0, out_alpha=np.zeros(3))

    def test_out_alpha_dtype_mismatch_is_rejected(self):
        f = self._wrapped()
        with pytest.raises(AssertionError, match="dtype mismatch"):
            f(np.array([20.0, 50.0]), 1500.0, out_alpha=np.zeros(2, dtype=np.float32))

    def test_extra_args_are_forwarded(self):
        f = self._wrapped()
        nus = np.array([20.0, 50.0])
        np.testing.assert_allclose(f(nus, 1500.0, 3.0), 3.0 * nus * 1500.0)

    def test_descending_frequencies_rejected(self):
        """Korg's contained_slice assumes ascending ν; say so instead of silently
        returning garbage (the previous implementation accepted descending input
        and then indexed it with an ascending slice)."""
        f = self._wrapped()
        with pytest.raises(ValueError, match="sorted in increasing order"):
            f(np.array([90.0, 50.0, 20.0]), 1500.0)

    def test_unsorted_frequencies_rejected(self):
        f = self._wrapped()
        with pytest.raises(AssertionError, match="sorted"):
            f(np.array([20.0, 90.0, 50.0]), 1500.0)

    def test_scalar_input_rejected(self):
        f = self._wrapped()
        with pytest.raises(ValueError, match="1-D array"):
            f(np.float64(20.0), 1500.0)

    def test_single_element_array(self):
        f = self._wrapped()
        np.testing.assert_allclose(f(np.array([50.0]), 1500.0), [50.0 * 1500.0])
        np.testing.assert_array_equal(f(np.array([5.0]), 1500.0), [0.0])

    def test_default_bounds_are_unrestricted(self):
        f = bounds_checked_absorption(_kernel)
        nus = np.array([1e-3, 1e3, 1e30])
        assert np.all(f(nus, 1.0) > 0)

    def test_wrapper_exposes_its_bounds(self):
        f = self._wrapped()
        assert f.nu_bound is self.NU_BOUND
        assert f.temp_bound is self.T_BOUND


class TestClampToBound:
    """clamp_to_bound must never hand a zero or an infinity to the arithmetic."""

    def test_identity_inside_the_interval(self):
        iv = closed_interval(10.0, 100.0)
        for x in (10.0, 50.0, 100.0):
            assert float(clamp_to_bound(x, iv, 1.0)) == x

    def test_folds_outside_values_inward(self):
        iv = closed_interval(10.0, 100.0)
        assert float(clamp_to_bound(-5.0, iv, 1.0)) == pytest.approx(10.0)
        assert float(clamp_to_bound(1e6, iv, 1.0)) == pytest.approx(100.0)

    def test_uses_the_floor_when_the_interval_reaches_zero(self):
        iv = Interval(0.0, np.inf)
        assert float(clamp_to_bound(0.0, iv, 1000.0)) == 1000.0
        assert float(clamp_to_bound(-1.0, iv, 1000.0)) == 1000.0

    def test_result_is_strictly_positive(self):
        """A zero substitute is not good enough: sqrt(0) has infinite derivative
        and 0*inf is NaN, so the cotangent would still be poisoned."""
        for iv in (Interval(0.0, np.inf), closed_interval(0.0, 1e19)):
            assert float(clamp_to_bound(0.0, iv, 1.0)) > 0.0
            assert float(clamp_to_bound(-1e30, iv, 1.0)) > 0.0

    def test_infinite_upper_bound_is_left_unbounded(self):
        """Substituting a finite sentinel would silently alter in-bounds values."""
        iv = Interval(0.0, np.inf)
        assert float(clamp_to_bound(1e300, iv, 1.0)) == 1e300

    def test_non_positive_floor_rejected(self):
        with pytest.raises(ValueError, match="strictly positive"):
            clamp_to_bound(1.0, Interval(0.0, np.inf), 0.0)
        with pytest.raises(ValueError, match="strictly positive"):
            clamp_to_bound(1.0, Interval(0.0, np.inf), -1.0)

    def test_floor_above_upper_bound_rejected(self):
        with pytest.raises(ValueError, match="exceeds the interval upper bound"):
            clamp_to_bound(1.0, closed_interval(0.0, 5.0), 10.0)


class TestInBoundsMask:
    """The JAX-traceable mask, including Korg's ν/T asymmetry."""

    def test_nu_bound_is_inclusive(self):
        iv = closed_interval(10.0, 100.0)
        assert bool(in_bounds_mask(iv.lower, 1.0, iv, None))
        assert bool(in_bounds_mask(iv.upper, 1.0, iv, None))

    def test_temp_bound_is_exclusive_on_the_nudged_bounds(self):
        iv = closed_interval(1400.0, 10080.0)
        assert bool(in_bounds_mask(1.0, 1400.0, None, iv))     # nudged, so admitted
        assert bool(in_bounds_mask(1.0, 10080.0, None, iv))
        assert not bool(in_bounds_mask(1.0, iv.lower, None, iv))
        assert not bool(in_bounds_mask(1.0, iv.upper, None, iv))

    def test_none_means_unrestricted(self):
        assert bool(in_bounds_mask(1e30, 1e30, None, None))

    def test_vectorises_over_frequency(self):
        iv = closed_interval(10.0, 100.0)
        m = in_bounds_mask(jnp.array([1.0, 50.0, 1000.0]), 1.0, iv, None)
        assert list(np.asarray(m)) == [False, True, False]

    def test_traceable_under_jit(self):
        iv = closed_interval(10.0, 100.0)
        tv = closed_interval(1000.0, 2000.0)
        f = jax.jit(lambda nu, T: in_bounds_mask(nu, T, iv, tv))
        assert bool(f(50.0, 1500.0))
        assert not bool(f(5.0, 1500.0))
        assert not bool(f(50.0, 5.0))


